"""Engine, schema creation and deterministic seeding (task T08).

``python -m arbitrageiq.db init`` creates the schema; ``python -m arbitrageiq.db
seed`` loads ``data/sample/`` and prints what it inserted. Neither command may
invent real data: the fixtures are synthetic and generated by
``scripts/make_sample_data.py`` (``plans/SECURITY.md`` §4.1).

Three tables are seeded — ``products``, ``transactions`` and
``fee_assumptions``. ``import_batches`` is written by the import path (T09) and
``budget_plan_runs`` / ``budget_plan_lines`` by the budget simulator (T11, T12),
so this module must not invent rows for them.

All money is parsed to ``Decimal`` from the CSV text, never through a float
(``plans/DECISIONS.md`` ADR-006).
"""

from __future__ import annotations

import csv
import json
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

from sqlalchemy import Engine, create_engine, func, insert, select

from arbitrageiq import models
from arbitrageiq.config import FeeAssumptions

REPO_ROOT = Path(__file__).resolve().parents[2]
SAMPLE_DIR = REPO_ROOT / "data" / "sample"
PRODUCTS_CSV = SAMPLE_DIR / "products_sample.csv"
TRANSACTIONS_CSV = SAMPLE_DIR / "transactions_sample.csv"

#: Disposable local database. ``*.db`` is gitignored, and it must never live
#: under ``data/sample/`` (``plans/ARCHITECTURE.md`` §2).
DEFAULT_DB_PATH = REPO_ROOT / "data" / "private" / "arbitrageiq.db"

_MONEY_PRODUCT_COLUMNS = (
    "supplier_unit_cost",
    "inbound_unit_cost",
    "packaging_unit_cost",
    "target_price",
)
_INT_PRODUCT_COLUMNS = ("current_stock", "min_order_qty", "max_supply")
_MONEY_TRANSACTION_COLUMNS = (
    "selling_price",
    "discount_per_unit",
    "refund_per_returned_unit",
    "settlement_fees_total",
    "ads_cost",
    "other_charges",
)


def default_url() -> str:
    """SQLite URL for the disposable local database."""
    return f"sqlite:///{DEFAULT_DB_PATH.as_posix()}"


def make_engine(url: str | None = None) -> Engine:
    """Create an engine. The default target's parent directory is created."""
    if url is None:
        DEFAULT_DB_PATH.parent.mkdir(parents=True, exist_ok=True)
        url = default_url()
    return create_engine(url)


def init(engine: Engine) -> None:
    """Create every table in the ERD (``plans/ARCHITECTURE.md`` §5)."""
    models.Base.metadata.create_all(engine)


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _optional_money(value: str | None) -> Decimal | None:
    if value is None or value.strip() == "":
        return None
    return Decimal(value)


def _money(value: str) -> Decimal:
    return Decimal(value)


def seed(engine: Engine) -> dict[str, object]:
    """Load the bundled synthetic fixtures. Returns the printed summary."""
    products = []
    for row in _rows(PRODUCTS_CSV):
        record = {name: row[name] for name in ("sku", "name", "category")}
        for name in _MONEY_PRODUCT_COLUMNS:
            record[name] = _money(row[name])
        for name in _INT_PRODUCT_COLUMNS:
            record[name] = int(row[name])
        raw_date = (row.get("cost_updated_on") or "").strip()
        record["cost_updated_on"] = date.fromisoformat(raw_date) if raw_date else None
        products.append(record)

    transactions = []
    for row in _rows(TRANSACTIONS_CSV):
        record = {
            "transaction_id": row["transaction_id"],
            "order_date": date.fromisoformat(row["order_date"]),
            "sku": row["sku"],
            "units_sold": int(row["units_sold"]),
            "returned_units": int(row["returned_units"]),
        }
        for name in _MONEY_TRANSACTION_COLUMNS:
            raw = (row.get(name) or "").strip()
            record[name] = (
                _optional_money(raw)
                if name
                in {
                    "refund_per_returned_unit",
                    "settlement_fees_total",
                }
                else _money(raw)
            )
        record["import_batch_id"] = None
        transactions.append(record)

    defaults = FeeAssumptions()
    assumptions_row = {
        "effective_from": defaults.effective_from,
        "note": defaults.note,
        "fee_gst_recoverable": defaults.fee_gst_recoverable,
    }
    for key in FeeAssumptions.__dataclass_fields__:
        if key in assumptions_row or key in {"effective_from", "note"}:
            continue
        assumptions_row[key] = getattr(defaults, key)

    with engine.begin() as connection:
        connection.execute(insert(models.products), products)
        connection.execute(insert(models.transactions), transactions)
        connection.execute(insert(models.fee_assumptions), [assumptions_row])
        summary = {
            "seeded": True,
            "products": connection.execute(
                select(func.count()).select_from(models.products)
            ).scalar_one(),
            "transactions": connection.execute(
                select(func.count()).select_from(models.transactions)
            ).scalar_one(),
            "fee_assumptions": connection.execute(
                select(func.count()).select_from(models.fee_assumptions)
            ).scalar_one(),
        }
    return summary


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if not args or args[0] not in {"init", "seed"}:
        print("usage: python -m arbitrageiq.db [init|seed]", file=sys.stderr)
        return 2
    engine = make_engine()
    if args[0] == "init":
        init(engine)
        print(json.dumps({"created": True, "path": str(DEFAULT_DB_PATH)}))
        return 0
    init(engine)
    print(json.dumps(seed(engine)))
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
